#!/usr/bin/env bash
# PreToolUse hook scoped to the test-writer agent (.claude/agents/test-writer.md).
# Enforces docs/PLAN.md §3.1: the test writer never sees implementation and
# only writes test files. Layered with the sparse worktree, CI role-paths and review.
#   Read / Grep         : no implementation paths; Grep must be scoped to allowed roots or *_test.go
#   Glob                : allowed (file names only, no contents)
#   Write / Edit        : test paths only
#   Bash                : allowlist of git / file-listing commands that cannot print implementation;
#                         grep/rg only with explicit test/docs targets; no substitution or redirection
# Exit 2 = block; stderr is shown to the agent.
set -euo pipefail
set -f

input=$(cat)
tool=$(jq -r '.tool_name // empty' <<<"$input")
block() { echo "blocked by scripts/claude/test-writer-guard.sh: $1 (docs/PLAN.md §3.1)" >&2; exit 2; }

impl_re='(^|/)(cmd|internal|migrations)(/|$)|(^|/)web/src(/|$)'
test_re='(_test\.go$|(^|/)testdata(/|$)|(^|/)test/|(^|/)web/tests(/|$)|\.spec\.ts$)'

is_impl() { [[ "$1" =~ $impl_re ]] && ! [[ "$1" =~ $test_re ]]; }
is_test() { [[ "$1" =~ $test_re ]]; }

case "$tool" in
  Read)
    p=$(jq -r '.tool_input.file_path // empty' <<<"$input")
    is_impl "$p" && block "reading implementation file '$p'"
    ;;

  Grep)
    p=$(jq -r '.tool_input.path // empty' <<<"$input")
    g=$(jq -r '.tool_input.glob // empty' <<<"$input")
    [[ -n "$p" ]] && is_impl "$p" && block "searching implementation path '$p'"
    # Unscoped or root-level searches would read implementation contents.
    allowed_root='(^|/)(docs|test|testdata|web/tests|\.claude)(/|$)|\.html$|\.md$'
    if ! { [[ -n "$p" && "$p" =~ $allowed_root ]] || [[ "$g" == *_test.go || "$g" == *.spec.ts ]]; }; then
      block "Grep must target docs/, test/, testdata/, web/tests/, .claude/ or use glob '*_test.go'"
    fi
    ;;

  Glob) ;;

  Write|Edit|MultiEdit|NotebookEdit)
    p=$(jq -r '.tool_input.file_path // .tool_input.notebook_path // empty' <<<"$input")
    # The seed manifest is generated by the seed code (docs/contracts/seed.md): read-only for the test writer.
    [[ "$p" == *testdata/seed/manifest.json ]] && block "the seed manifest is generated by the seed code; the test writer reads it, never writes it"
    is_test "$p" || block "the test writer may only write test files (*_test.go, test/, testdata/, web/tests/), not '$p'"
    ;;

  Bash)
    cmd=$(jq -r '.tool_input.command // empty' <<<"$input")
    # Command substitution, process substitution and redirection would run or read
    # anything behind an allowed command name (e.g. echo $(cat internal/x.go)).
    [[ "$cmd" == *'$('* || "$cmd" == *'`'* || "$cmd" == *'<'* || "$cmd" == *'>'* ]] \
      && block "command substitution and redirection are not allowed (use git commit -m, not a heredoc)"
    while IFS= read -r seg; do
      seg="${seg#"${seg%%[![:space:]]*}"}"
      [[ -z "$seg" ]] && continue
      # shellcheck disable=SC2206
      w=($seg)
      case "${w[0]}" in
        ls|pwd|mkdir|gofmt|echo|wc) ;;
        grep|rg)
          # Only test paths and docs (docs/PLAN.md §3.1): every target must be named, relative,
          # without '..', and inside a test root; no target means stdin or the whole tree.
          [[ "$seg" == *'$'* ]] && block "variables are not allowed in ${w[0]} targets"
          targets=() pattern_given=0 opts_done=0 skip=0
          for a in "${w[@]:1}"; do
            if (( skip )); then skip=0; continue; fi
            if (( ! opts_done )); then
              [[ "$a" =~ ^-[^-]*f ]] && block "${w[0]} -f reads a pattern file from outside test paths"
              case "$a" in
                --) opts_done=1; continue ;;
                --file|--file=*|--pre|--pre=*|--pre-glob*) block "${w[0]} $a can read or run files outside test paths" ;;
                -e|--regexp) pattern_given=1; skip=1; continue ;;
                -e*|--regexp=*) pattern_given=1; continue ;;
                -g|-t|-T|-A|-B|-C|-m|-M|-j|-d|-D|--glob|--iglob|--type|--type-not|--max-count|--context|--after-context|--before-context|--max-columns|--threads|--include|--exclude|--exclude-dir)
                  skip=1; continue ;;
                -*) continue ;;
              esac
            fi
            if (( ! pattern_given )); then pattern_given=1; continue; fi
            targets+=("$a")
          done
          (( ${#targets[@]} )) || block "${w[0]} needs explicit test paths (test, testdata, web/tests, docs, *_test.go); stdin and the working directory are not allowed"
          for t in "${targets[@]}"; do
            t="${t//\"/}"; t="${t//\'/}"; t="${t#./}"
            [[ "$t" == /* || "$t" == '~'* || "/$t/" == */../* || "/$t" =~ /\.env ]] \
              && block "${w[0]} target '$t' is outside the test paths"
            [[ "$t" =~ ^(test|testdata|web/tests|docs)(/.*)?$ || "$t" =~ (^|/)testdata(/|$) \
               || "$t" == *_test.go || "$t" == DECISIONS.md ]] \
              || block "${w[0]} may only search test paths and docs (test, testdata, web/tests, docs, *_test.go, DECISIONS.md), not '$t'"
          done
          ;;
        git)
          case "${w[1]:-}" in
            status|add|commit|push|fetch|rev-parse) ;;
            worktree)
              [[ "${w[2]:-}" == "list" ]] || block "only 'git worktree list'; worktrees are managed by scripts/test-writer-worktree.sh and scripts/worktree-remove.sh"
              ;;
            branch)
              [[ "$seg" =~ (^|[[:space:]])(-d|-D|--delete|-f|--force|-m|-M|--move)([[:space:]]|$) ]] && block "the test writer may not delete, move or force branches"
              ;;
            switch)
              [[ "$seg" =~ (^|[[:space:]])(-f|--force|--discard-changes)([[:space:]]|$) ]] && block "git switch --force discards uncommitted work"
              ;;
            log)
              [[ "$seg" =~ (^|[[:space:]])(-p|--patch|-u|--stat|--name-only|--name-status|--follow)([[:space:]]|$) ]] \
                && block "git log may not show diffs or file lists"
              ;;
            diff)
              [[ "$seg" =~ (^|[[:space:]])--cached([[:space:]]|$) ]] || block "only 'git diff --cached' (your own staged tests) is allowed"
              ;;
            sparse-checkout)
              [[ "${w[2]:-}" == "list" ]] || block "the sparse checkout is set up by scripts/test-writer-worktree.sh, not changed by the test writer"
              ;;
            *) block "git ${w[1]:-} can expose implementation from the object store" ;;
          esac
          ;;
        *) block "command '${w[0]}' is not on the test writer's allowlist (use Read/Glob/Write/Edit)" ;;
      esac
    done < <(printf '%s\n' "$cmd" | tr ';&|' '\n\n\n')
    ;;
esac
exit 0
